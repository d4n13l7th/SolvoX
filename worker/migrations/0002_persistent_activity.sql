CREATE TABLE IF NOT EXISTS matches (
  id INTEGER PRIMARY KEY AUTOINCREMENT, ts TEXT NOT NULL, match_id TEXT NOT NULL,
  level_id INTEGER, mode TEXT, player TEXT NOT NULL, opponent TEXT,
  answered INTEGER NOT NULL DEFAULT 0, correct INTEGER NOT NULL DEFAULT 0,
  accuracy INTEGER NOT NULL DEFAULT 0, score INTEGER NOT NULL DEFAULT 0,
  hp_remaining INTEGER NOT NULL DEFAULT 0, wins INTEGER NOT NULL DEFAULT 0,
  draw INTEGER NOT NULL DEFAULT 0, losses INTEGER NOT NULL DEFAULT 0,
  duration_sec INTEGER NOT NULL DEFAULT 0, total_questions INTEGER NOT NULL DEFAULT 10,
  hints_used INTEGER NOT NULL DEFAULT 0, decisive_question TEXT, decisive_concept TEXT
);
CREATE INDEX IF NOT EXISTS idx_matches_player_ts ON matches (player, ts);
CREATE INDEX IF NOT EXISTS idx_matches_ts ON matches (ts);
CREATE TABLE IF NOT EXISTS feedback (id INTEGER PRIMARY KEY AUTOINCREMENT, ts TEXT NOT NULL, payload TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS evaluations (id INTEGER PRIMARY KEY AUTOINCREMENT, ts TEXT NOT NULL, payload TEXT NOT NULL);

const fs = require('fs');
const path = require('path');
const root = __dirname;
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const exists = (file) => fs.existsSync(path.join(root, file));
const must = (value, message) => { if (!value) throw new Error(message); };
const worker = read('worker/src/index.js');
const room = read('worker/src/room.js');
const store = read('worker/src/store.js');
const config = read('frontend/src/config.js');
const realtime = read('frontend/src/services/realtime.js');
const runtimeConfig = read('frontend/public/config.js');
const components = fs.readdirSync(path.join(root, 'frontend/src/components')).filter((file) => file.endsWith('.jsx')).map((file) => read(`frontend/src/components/${file}`)).join('\n');
must(!exists('backend') && !exists('server.js') && !exists('Dockerfile') && !exists('deploy-koyeb.sh'), 'Legacy Express deployment files remain');
must(exists('worker/migrations/0001_single_player.sql') && exists('worker/migrations/0002_persistent_activity.sql'), 'D1 migrations are incomplete');
must(worker.includes('SOLVOX_ROOM') && worker.includes('createSinglePlayerStore'), 'Worker bindings are incomplete');
must(worker.includes("'/api/dashboard'") && worker.includes("'/api/player-profile'"), 'Worker statistics routes are missing');
must(store.includes('INSERT INTO matches') && store.includes('INSERT INTO feedback') && store.includes('INSERT INTO evaluations'), 'Worker activity storage is not persistent');
must(room.includes('recordMatch(this.env.DB'), 'Finished multiplayer matches are not persisted through D1');
must(config.includes('export function apiUrl') && runtimeConfig.includes('solvox-worker.workers.dev'), 'Frontend Worker routing is missing');
must(!components.includes("socket.io-client") && !realtime.includes("socket.io-client"), 'Socket.IO client must not be used');
must(!/fetch\(\s*['\"`]\/api\//.test(components), 'A frontend component bypasses apiUrl()');
console.log('Solvox production contract PASS');
